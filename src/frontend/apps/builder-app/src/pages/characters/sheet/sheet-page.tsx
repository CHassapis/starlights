function SpellPage({ title, casting, spells }: { title: string; casting: SheetSpellcasting | null; spells: SheetSpell[] }) {
  const levels = [...new Set([...spells.map((s) => s.level), ...Object.keys(casting?.slots ?? {}).map(Number)])].sort((a, b) => a - b);
  return (
    <div className={PAGE}>
      <div className="mb-4 flex items-center gap-4 rounded-lg border-2 border-neutral-800 bg-neutral-100 px-4 py-3">
        <div className="flex-1 rounded-md border-2 border-neutral-800 bg-white px-3 py-2 text-center text-lg">{title}</div>
        {[
          ["Spellcasting ability", casting?.ability],
          ["Spell attack bonus", casting ? fmt(casting.attackBonus) : ""],
          ["Saving throw DC", casting?.saveDc],
          ["Spells to prepare", casting?.prepare ?? ""],
        ].map(([label, value]) => (
          <div key={label as string} className="text-center">
            <div className="min-w-20 rounded-md border-2 border-neutral-800 bg-white px-2 py-1 text-sm">{value || " "}</div>
            <Label className="mt-1">{label}</Label>
          </div>
        ))}
      </div>
      <div className="space-y-3">
        {levels.map((level) => {
          const list = spells.filter((s) => s.level === level);
          const slots = casting?.slots[level] ?? 0;
          return (
            <div key={level} className="rounded-lg border border-neutral-300 p-2">
              <div className="mb-1 flex items-center gap-3 rounded bg-neutral-400 px-2 py-0.5 text-[8px] font-semibold uppercase tracking-wider text-white">
                <span>{level === 0 ? "Cantrips" : `${["", "1st", "2nd", "3rd", "4th", "5th", "6th", "7th", "8th", "9th"][level]} level`}</span>
                {slots > 0 && (
                  <span className="ms-auto flex items-center gap-1">
                    {slots} spell slots
                    {Array.from({ length: slots }, (_, i) => (
                      <span key={i} className="size-2 rounded-full bg-white" />
                    ))}
                  </span>
                )}
              </div>
              <div className="grid grid-cols-3 gap-x-3 gap-y-1">
                {list.map((spell) => (
                  <div key={spell.name + spell.origin} className="flex items-center gap-1.5 rounded bg-neutral-100 px-1.5 py-0.5 text-[9px]">
                    <span className="size-2 shrink-0 rounded-full border border-neutral-500" />
                    <span className="truncate">
                      {spell.name}
                      {!casting && spell.origin ? <span className="text-neutral-500"> ({spell.origin.replace(/^Level \d+: /, "")})</span> : null}
                    </span>
                  </div>
                ))}
              </div>
            </div>
          );
        })}
      </div>
      <Footer />
    </div>
  );
}

function SpellCard({ spell }: { spell: SheetSpell }) {
  const html = DOMPurify.sanitize(spell.description, { FORBID_ATTR: ["style"] });
  return (
    <div className="flex h-[318px] flex-col overflow-hidden rounded-lg border-2 border-neutral-700 p-2">
      <div className="rounded bg-neutral-200 py-0.5 text-center text-[12px] font-semibold">{spell.name}</div>
      <div className="my-1 text-center text-[8px] italic">{spellLevelLine(spell)}</div>
      <div className="grid grid-cols-[62px_1fr] gap-x-2 gap-y-0.5 text-[8px]">
        {[
          ["Casting time", spell.time + (spell.ritual ? " (ritual)" : "")],
          ["Range", spell.range],
          ["Duration", spell.duration],
          ["Components", spell.components],
        ].map(([label, value]) => (
          <div key={label} className="contents">
            <span className="rounded-l bg-neutral-100 px-1 text-right uppercase text-neutral-500">{label}</span>
            <span className="truncate rounded-r bg-neutral-100 px-1">{value}</span>
          </div>
        ))}
      </div>
      <div className="mt-1.5 min-h-0 flex-1 overflow-hidden text-[7.5px] leading-[1.3] [&_p]:mb-1" dangerouslySetInnerHTML={{ __html: html }} />
      <div className="mt-1 flex justify-between text-[7px] italic text-neutral-600">
        <span className="truncate">{spell.origin.replace(/^Level \d+: /, "")}</span>
        <span className="truncate">{spell.source}</span>
      </div>
    </div>
  );
}

function SpellCardPages({ spells }: { spells: SheetSpell[] }) {
  const pages: SheetSpell[][] = [];
  for (let i = 0; i < spells.length; i += 9) pages.push(spells.slice(i, i + 9));
  return (
    <>
      {pages.map((page, i) => (
        <div key={i} className={PAGE}>
          <div className="grid grid-cols-3 gap-3">
            {page.map((spell) => (
              <SpellCard key={spell.name + spell.origin} spell={spell} />
            ))}
          </div>
          <Footer />
        </div>
      ))}
    </>
  );
}

export function CharacterSheetPage() {
  const { id = "" } = useParams();
  const { data, isLoading, error } = useSheetData(id);
  const [exporting, setExporting] = useState(false);

  // Aurora's own sheet templates, filled in (see lib/aurora-sheet); "view" opens it in the browser's PDF viewer
  async function makePdf(view: boolean) {
    if (!data) return;
    const tab = view ? window.open("", "_blank") : null;
    setExporting(true);
    try {
      const bytes = await buildAuroraSheet(data);
      const url = URL.createObjectURL(new Blob([bytes as BlobPart], { type: "application/pdf" }));
      if (tab) {
        tab.location.href = url;
      } else {
        const link = document.createElement("a");
        link.href = url;
        link.download = `${data.name.replace(/[^\w\- ]+/g, "").trim() || "character"}.pdf`;
        link.click();
      }
      setTimeout(() => URL.revokeObjectURL(url), 60_000);
    } catch (e) {
      tab?.close();
      toast.error("Could not make the PDF", { description: (e as Error).message });
    } finally {
      setExporting(false);
    }
  }

  if (isLoading) return <Spinner className="mx-auto my-24 size-6" />;
  if (error || !data)
    return (
      <p className="py-24 text-center text-muted-foreground">
        {(error as { status?: number } | null)?.status === 401 ? "This character's player locked their characters with a password." : "This character could not be loaded."}
      </p>
    );

  const [mainFeatures, moreFeatures] = split(data.features, 3600);
  const notes = [data.story.backstory && data.story.backstory.length > 1600 ? data.story.backstory : "", data.story.notes ?? ""].filter(Boolean).join("\n\n");
  const allSpells = [...data.spellcasting.flatMap((c) => c.spells), ...data.otherSpells].sort((a, b) => a.level - b.level || a.name.localeCompare(b.name));

  return (
    <div className="min-h-screen bg-neutral-300 py-6 print:bg-white print:py-0">
      <div className="mx-auto mb-4 flex w-[816px] max-w-full items-center gap-2 px-4 print:hidden">
        <Button variant="secondary" asChild>
          <Link to={`/characters/${id}`}>
            <ArrowLeftIcon /> Back to the builder
          </Link>
        </Button>
        <span className="flex-1" />
        <Button variant="secondary" onClick={() => window.print()}>
          <PrinterIcon /> Print
        </Button>
        <Button variant="secondary" onClick={() => makePdf(true)} disabled={exporting}>
          <FileTextIcon /> View PDF
        </Button>
        <Button onClick={() => makePdf(false)} disabled={exporting}>
          {exporting ? <Spinner /> : <DownloadIcon />} Download PDF
        </Button>
      </div>
      <div className="overflow-x-auto">
        <MainPage data={data} features={mainFeatures} />
        {moreFeatures.length > 0 && <FeaturesPage features={moreFeatures} />}
        <DetailsPage data={data} />
        <InventoryPage data={data} />
        {notes && <TextPage title={`${data.name}: Backstory & notes`} text={notes} />}
        {data.spellcasting.map((c) => (
          <SpellPage key={c.name} title={c.name} casting={c} spells={c.spells} />
        ))}
        {data.otherSpells.length > 0 && <SpellPage title="Other Spells" casting={null} spells={data.otherSpells} />}
        {allSpells.length > 0 && <SpellCardPages spells={allSpells} />}
      </div>
    </div>
  );
}

