/*
 * The character sheet in the layout Aurora prints: main page, details, inventory, notes, spellcasting and spell
 * cards. Pages are US Letter at 96 dpi (816 × 1056 px); "Download PDF" makes Aurora's own sheet (lib/aurora-sheet).
 */

const PAGE = "sheet-page relative mx-auto mb-8 h-[1056px] w-[816px] overflow-hidden bg-white p-9 text-black shadow-lg print:mb-0 print:shadow-none";
const fmt = (n: number) => (n >= 0 ? `+${n}` : `${n}`);

function Label({ children, className }: { children: ReactNode; className?: string }) {
  return <div className={cn("text-[7.5px] font-semibold uppercase tracking-wider text-neutral-600", className)}>{children}</div>;
}

function Frame({ label, children, className, labelPosition = "bottom" }: { label?: string; children?: ReactNode; className?: string; labelPosition?: "top" | "bottom" }) {
  return (
    <div className={cn("relative flex flex-col rounded-lg border-2 border-neutral-800 bg-white px-2.5 py-2", className)}>
      {label && labelPosition === "top" && <Label className="mb-1">{label}</Label>}
      <div className="min-h-0 flex-1 overflow-hidden">{children}</div>
      {label && labelPosition === "bottom" && <Label className="mt-1 text-center">{label}</Label>}
    </div>
  );
}

function Pill({ children, className }: { children: ReactNode; className?: string }) {
  return <div className={cn("rounded-md bg-neutral-100 px-2 py-0.5 text-[10px]", className)}>{children}</div>;
}

function Dot({ proficiency }: { proficiency: Proficiency }) {
  return (
    <span className="inline-flex size-2.5 shrink-0 items-center justify-center rounded-full border border-neutral-700">
      {proficiency !== "none" && <span className={cn("rounded-full bg-neutral-800", proficiency === "expertise" ? "size-2" : "size-1.5")} />}
    </span>
  );
}

function FeatureText({ features }: { features: SheetFeature[] }) {
  return (
    <div className="space-y-1.5 text-[8.5px] leading-[1.3]">
      {features.map((f) => (
        <p key={f.title}>
          <b className="italic">
            {f.title}
            {f.usage || f.action ? ` (${[f.action, f.usage].filter(Boolean).join(", ")})` : ""}.
          </b>{" "}
          {f.text}
        </p>
      ))}
    </div>
  );
}

// how much feature text fits in a box before the rest continues on an extra page
function split(features: SheetFeature[], budget: number): [SheetFeature[], SheetFeature[]] {
  let used = 0;
  const index = features.findIndex((f) => (used += f.title.length + f.text.length + 60) > budget);
  return index < 0 ? [features, []] : [features.slice(0, index), features.slice(index)];
}

function Header({ data, fields }: { data: SheetData; fields: [string, string, string?][] }) {
  return (
    <div className="mb-4 grid grid-cols-[38%_1fr] gap-3">
      <div className="flex flex-col justify-end">
        <div className="rounded-md border-2 border-neutral-800 px-3 py-2 text-center text-xl">{data.name}</div>
        <Label className="mt-1 pl-2">Character name</Label>
      </div>
      <div className="grid grid-cols-4 gap-x-3 gap-y-1.5 rounded-lg border-2 border-neutral-800 px-3 py-2">
        {fields.map(([label, value, span]) => (
          <div key={label} className={cn("min-w-0", span)}>
            <div className="truncate border-b border-neutral-400 text-[11px] leading-5">{value || " "}</div>
            <Label>{label}</Label>
          </div>
        ))}
      </div>
    </div>
  );
}

function Footer() {
  return <p className="absolute inset-x-0 bottom-3 text-center text-[7px] text-neutral-500">This character sheet was generated by Starlights, with content from Aurora Legacy.</p>;
}

